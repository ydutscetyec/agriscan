import { useCallback, useEffect, useState } from 'react'
import { MessageSquare } from 'lucide-react'
import { Link } from 'react-router-dom'
import { api } from '../api/client'
import { PageHeader } from '../components/Layout'

/* Nothing on this page reaches a farmer until someone here presses Approve.
   The list is the gate made visible. */
export default function Recommendations() {
  const [items, setItems] = useState([])
  const [edited, setEdited] = useState({})
  const [busy, setBusy] = useState(null)
  const [error, setError] = useState(null)
  const [cleared, setCleared] = useState(0)

  const load = useCallback(() => {
    api.pendingRecommendations()
      .then((data) => setItems(data.recommendations))
      .catch((err) => setError(err.message))
  }, [])

  useEffect(() => { load() }, [load])

  async function act(rec, action) {
    setBusy(rec.id)
    setError(null)
    try {
      if (action === 'approve') {
        await api.approveRecommendation(rec.id, edited[rec.id] ?? rec.text)
      } else {
        const reason = window.prompt('Why is this being rejected?') || ''
        await api.rejectRecommendation(rec.id, reason)
      }
      setCleared((n) => n + 1)
      load()
    } catch (err) {
      setError(err.message)
    } finally {
      setBusy(null)
    }
  }

  return (
    <div className="as-content">
      <PageHeader
        eyebrow="Monitoring"
        icon={MessageSquare} title="Recommendations awaiting review" description="A farmer sees nothing here until it is approved. Edit the wording if it needs it; approving records your name against the advice." />

      {error && <div className="as-warn">{error}</div>}

      {items.length === 0 ? (
        <div className="as-empty">
          <p>Nothing is waiting for review.</p>
          <p style={{ fontSize: 13 }}>
            {cleared > 0 ? `You cleared ${cleared} this session. ` : ''}
            Recommendations are generated from technician-verified detections.
          </p>
        </div>
      ) : (
        items.map((rec) => (
          <div className="as-card plain" key={rec.id} style={{ marginBottom: 16 }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', gap: 12 }}>
              <h2 style={{ margin: 0 }}>{rec.condition_name}</h2>
              <div className="as-muted" style={{ fontSize: 12 }}>
                Detection <Link to={`/detections/${rec.detection_id}`}>#{rec.detection_id}</Link>
                {' · '}severity {rec.severity_band} · stage {rec.growth_stage}
              </div>
            </div>

            {rec.is_fallback && (
              <div className="as-warn" style={{ margin: '10px 0' }}>
                No knowledge base record matched this condition, so the system produced
                only the referral text. Approving it sends the farmer to a technician,
                which is the correct outcome when there is no sourced guidance.
              </div>
            )}

            <textarea
              className="as-input"
              rows={rec.is_fallback ? 2 : 8}
              value={edited[rec.id] ?? rec.text}
              onChange={(e) => setEdited({ ...edited, [rec.id]: e.target.value })}
              style={{ margin: '10px 0', fontFamily: 'inherit' }}
            />

            {Array.isArray(rec.source_refs) && rec.source_refs.length > 0 && (
              <div style={{ fontSize: 12, marginBottom: 10 }}>
                <strong>Sources:</strong>{' '}
                {rec.source_refs.map((s, i) => (
                  <span key={i} className="as-muted">
                    {s.title} ({s.publisher}{s.year ? `, ${s.year}` : ''})
                    {s.content_status !== 'REVIEWED' && (
                      <strong style={{ color: 'var(--sev-severe)' }}> — {s.content_status}</strong>
                    )}
                    {i < rec.source_refs.length - 1 ? ' · ' : ''}
                  </span>
                ))}
              </div>
            )}

            <div style={{ display: 'flex', gap: 8 }}>
              <button className="as-btn" disabled={busy === rec.id} onClick={() => act(rec, 'approve')}>
                Approve and publish
              </button>
              <button className="as-btn secondary" disabled={busy === rec.id} onClick={() => act(rec, 'reject')}>
                Reject
              </button>
              <span className="as-muted" style={{ fontSize: 12, alignSelf: 'center' }}>
                Generated by {rec.generated_by}
              </span>
            </div>
          </div>
        ))
      )}
    </div>
  )
}
